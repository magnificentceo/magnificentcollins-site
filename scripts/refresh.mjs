// Refreshes two things for the website:
//   1. Streaming links for each song, searched on the Austrian storefronts where the service has one.
//      Writes site/data/links-at.js. Links already in site/data/releases.js always win.
//   2. Platform icons (SVG) from Simple Icons (CC0). Writes into site/assets/icons/.
//
// Runs every two weeks from the scheduled GitHub Actions workflow. Set FORCE=1 to run now.
// Spotify needs SPOTIFY_CLIENT_ID and SPOTIFY_CLIENT_SECRET (GitHub repository secrets). Without them, Spotify is skipped.

import { readFile, writeFile, copyFile, stat } from "node:fs/promises";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import path from "node:path";
import vm from "node:vm";

const here = path.dirname(fileURLToPath(import.meta.url));
const siteDir = path.join(here, "..", "site");
const ARTIST = "Magnificent Collins";
const INTERVAL_DAYS = 13; // "every 2 weeks", with a day of slack so a Monday run can't be skipped

// Titles as the streaming services list them, where they differ from the catalogue title.
const SEARCH_TITLE = {
  "the-way-i-know-how": "The Way I Know How"
};

// Simple Icons slug for each icon file the site uses. Only icons that come from Simple Icons are refreshed here.
// Font Awesome icons (Spotify, YouTube, Deezer, and the rest) and Arcticons (Boomplay, Anghami) are left alone.
const ICON_FILES = {
  "apple-music.svg": "siApplemusic",
  "youtube-music.svg": "siYoutubemusic",
  "tidal.svg": "siTidal",
  "audiomack.svg": "siAudiomack",
  "pandora.svg": "siPandora",
  "iheart.svg": "siIheartradio"
};

// ---------- helpers (pure, tested) ----------

export function norm(s) {
  return String(s || "")
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

function artistMatches(name) {
  return norm(name) === norm(ARTIST);
}

// Exact match after normalizing, so "WAKA (Remix)" never stands in for "WAKA" by accident.
function titleMatches(found, wanted) {
  const f = norm(found);
  return f.length > 0 && f === norm(wanted);
}

// Apple Music: iTunes Search API with country=AT returns Austrian storefront URLs (/at/).
export function pickAppleMatch(results, title) {
  for (const r of results || []) {
    if (!r || r.wrapperType && r.wrapperType !== "track") continue;
    if (!artistMatches(r.artistName) || !titleMatches(r.trackName, title)) continue;
    const url = r.trackViewUrl || r.collectionViewUrl;
    if (typeof url === "string" && url.startsWith("https://music.apple.com/at/")) return url;
  }
  return null;
}

// Deezer: public API, no key. Deezer is not Austria-specific, but it is available there.
export function pickDeezerMatch(data, title) {
  for (const t of data || []) {
    if (!t || !artistMatches(t.artist && t.artist.name) || !titleMatches(t.title, title)) continue;
    if (typeof t.link === "string" && t.link.startsWith("https://www.deezer.com/")) return t.link;
  }
  return null;
}

// Spotify: search with market=AT, so only tracks playable in Austria come back.
export function pickSpotifyMatch(items, title) {
  for (const t of items || []) {
    const artists = (t && t.artists) || [];
    if (!artists.some((a) => artistMatches(a.name)) || !titleMatches(t.name, title)) continue;
    const url = t.external_urls && t.external_urls.spotify;
    if (typeof url === "string" && url.startsWith("https://open.spotify.com/")) return url;
  }
  return null;
}

// Returns the links.js file body. Pure, so it can be tested.
export function buildLinksFile(songs, generatedIso) {
  const body = JSON.stringify({ generated: generatedIso, songs }, null, 2);
  return (
    "/* Generated by scripts/refresh.mjs. Do not edit by hand: changes are overwritten on the next refresh.\n" +
    "   Links here are added only for services that data/releases.js does not already list. */\n" +
    "window.SITE_LINKS = " + body + ";\n"
  );
}

export function svgFromIcon(icon) {
  return (
    '<svg role="img" viewBox="0 0 24 24" xmlns="http://www.w3.org/2000/svg"><title>' +
    icon.title + "</title><path d=\"" + icon.path + "\"/></svg>\n"
  );
}

export function isDue(lastIso, nowMs, intervalDays = INTERVAL_DAYS) {
  if (!lastIso) return true;
  const last = Date.parse(lastIso);
  if (Number.isNaN(last)) return true;
  return nowMs - last >= intervalDays * 24 * 60 * 60 * 1000;
}

// ---------- network lookups (given an injected fetch so tests can fake them) ----------

async function getJson(fetchFn, url, init) {
  const res = await fetchFn(url, init);
  if (!res.ok) throw new Error(res.status + " from " + url.split("?")[0]);
  return res.json();
}

// `failed` collects the services whose lookup errored, so the caller can keep their previous links.
export async function lookupAll(title, { fetchFn, spotifyToken, failed = [] }) {
  const found = {};
  const wanted = SEARCH_TITLE[title.id] || title.title;

  try {
    const q = encodeURIComponent(ARTIST + " " + wanted);
    const data = await getJson(fetchFn, "https://itunes.apple.com/search?term=" + q + "&entity=song&country=AT&limit=25");
    const url = pickAppleMatch(data.results, wanted);
    if (url) found["Apple Music"] = url;
  } catch (e) { warn(title.id, "Apple Music", e); failed.push("Apple Music"); }

  try {
    const q = encodeURIComponent('artist:"' + ARTIST + '" track:"' + wanted + '"');
    const data = await getJson(fetchFn, "https://api.deezer.com/search?q=" + q);
    const url = pickDeezerMatch(data.data, wanted);
    if (url) found["Deezer"] = url;
  } catch (e) { warn(title.id, "Deezer", e); failed.push("Deezer"); }

  if (spotifyToken) {
    try {
      const q = encodeURIComponent('track:"' + wanted + '" artist:"' + ARTIST + '"');
      const data = await getJson(fetchFn, "https://api.spotify.com/v1/search?type=track&limit=10&market=AT&q=" + q,
        { headers: { Authorization: "Bearer " + spotifyToken } });
      const url = pickSpotifyMatch(data.tracks && data.tracks.items, wanted);
      if (url) found["Spotify"] = url;
    } catch (e) { warn(title.id, "Spotify", e); failed.push("Spotify"); }
  }
  return found;
}

async function spotifyToken(fetchFn) {
  const id = process.env.SPOTIFY_CLIENT_ID;
  const secret = process.env.SPOTIFY_CLIENT_SECRET;
  if (!id || !secret) return null;
  const basic = Buffer.from(id + ":" + secret).toString("base64");
  const res = await fetchFn("https://accounts.spotify.com/api/token", {
    method: "POST",
    headers: { Authorization: "Basic " + basic, "Content-Type": "application/x-www-form-urlencoded" },
    body: "grant_type=client_credentials"
  });
  if (!res.ok) throw new Error("Spotify token " + res.status);
  return (await res.json()).access_token;
}

function warn(songId, service, err) {
  console.warn("  skipped " + service + " for " + songId + ": " + (err && err.message ? err.message : err));
}

// ---------- main ----------

// Reads the links file from the last run, so a failed lookup can keep its old link.
async function loadPreviousLinks(linksPath) {
  try {
    const sandbox = { window: {} };
    vm.runInNewContext(await readFile(linksPath, "utf8"), sandbox, { filename: "links-at.js" });
    return (sandbox.window.SITE_LINKS && sandbox.window.SITE_LINKS.songs) || {};
  } catch {
    return {};
  }
}

async function loadCatalogue() {
  const src = await readFile(path.join(siteDir, "data", "releases.js"), "utf8");
  const sandbox = { window: {} };
  vm.runInNewContext(src, sandbox, { filename: "releases.js" });
  return sandbox.window.SITE_DATA;
}

async function refreshIcons() {
  const require = createRequire(import.meta.url);
  const si = require("simple-icons");
  const outDir = path.join(siteDir, "assets", "icons");
  for (const [file, key] of Object.entries(ICON_FILES)) {
    const icon = si[key];
    if (!icon) { console.warn("  no Simple Icons entry for " + key); continue; }
    await writeFile(path.join(outDir, file), svgFromIcon(icon));
    console.log("  icon " + file + " from Simple Icons " + key);
  }
}

async function main() {
  const fetchFn = globalThis.fetch;
  const linksPath = path.join(siteDir, "data", "links-at.js");
  const now = Date.now();

  let last = null;
  try {
    const existing = await readFile(linksPath, "utf8");
    const m = existing.match(/"generated":\s*"([^"]+)"/);
    last = m ? m[1] : null;
  } catch { /* first run */ }

  if (!process.env.FORCE && !isDue(last, now)) {
    console.log("Not due yet (last run " + last + "). Set FORCE=1 to run anyway.");
    return;
  }

  const data = await loadCatalogue();
  const token = await spotifyToken(fetchFn).catch((e) => { console.warn("Spotify skipped: " + e.message); return null; });
  if (!token) console.log("No Spotify credentials: Spotify links are not refreshed.");

  const previous = await loadPreviousLinks(linksPath);
  const songs = {};
  for (const release of data.releases) {
    console.log(release.id);
    const failed = [];
    const found = await lookupAll(release, { fetchFn, spotifyToken: token, failed });
    songs[release.id] = {};
    for (const s of Object.keys(found)) songs[release.id][s] = { url: found[s] };
    // A lookup that errored says nothing about the link, so keep whatever the last run found.
    for (const s of failed) {
      const old = previous[release.id] && previous[release.id][s];
      if (old && !songs[release.id][s]) songs[release.id][s] = old;
    }
    console.log("  found: " + (Object.keys(found).join(", ") || "nothing"));
  }

  await writeFile(linksPath, buildLinksFile(songs, new Date(now).toISOString()));
  await refreshIcons();
  console.log("Done.");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((e) => { console.error(e); process.exit(1); });
}
